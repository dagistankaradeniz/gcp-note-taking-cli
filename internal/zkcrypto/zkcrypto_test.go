// recoveryCredential.ts's comment: the plain libsodium-wrappers build
// omits crypto_pwhash/Argon2id entirely) into a real Chromium page via
// Playwright (about:blank isn't a secure context, so window.crypto.subtle
// is unavailable there -- a real localhost page was used instead) and
// running crypto_pwhash + the same HKDF-SHA256 combine recoveryCredential.ts
